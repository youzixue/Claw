"""板块营地展示口径：无业务关联概念的排除规则。

为什么这条规则必须放在 app 层
------------------------------
该规则原先只写在 `scripts/collect_pywencai_sectors.py`（一次性采集脚本）里。
但概念板块自改由调度器盘前路径写入（`scheduler._premarket` →
`_upsert_sector_info`）后，**调度器不经过那个脚本**，新发现的概念会以
`SectorInfo.is_excluded` 的列默认值 0 建库并出现在板块营地。
实测 2026-09-17：迁移到 `WencaiStreamSource` 后待写入 827 个概念，
其中 `2026中报预增` 属规则命中却不在库内 —— 即会被漏排除。
规则上移到 app 层，调度器与脚本共用同一份，避免两处口径漂移。

口径说明
--------
排的是**无业务关联**的板块（指数成分、资金通道、持股平台、股权类、
财报预告类），不是"表现不好"的板块。财报预告类名称随年份变化
（`2026中报预增` / `2025年报预增`），故用模式匹配而非枚举。

改这里的含义：只影响板块营地是否展示该板块，不影响个股映射、
板块生命周期、涨停归因或任何交易链路。
"""
from __future__ import annotations

# 无业务关联的概念板块 —— 采集/写入时自动标记 is_excluded=1（不展示在板块营地）
EXCLUDED_CONCEPT_NAMES: frozenset[str] = frozenset({
    # 资金通道 / 持股平台 / 指数成分
    "融资融券", "沪股通", "深股通", "证金持股", "国家大基金持股",
    "同花顺果指数", "同花顺漂亮100", "同花顺中特估100",
    "同花顺出海50", "同花顺新质50", "中国AI 50",
    # 上市状态类
    "ST板块", "新股与次新股", "注册制次新股", "科创次新股", "摘帽",
    # 股权/重组类
    "股权转让(并购重组)", "兵装重组概念",
    # 风格/资金偏好
    "高股息精选", "超级品牌", "专精特新", "独角兽概念",
    # 国企改革类
    "央企国企改革", "国企改革", "上海国企改革", "深圳国企改革",
    "中字头股票", "中芯国际概念", "中船系",
    # 参股金融类
    "参股保险", "参股券商", "参股银行", "信托概念", "期货概念", "PPP概念",
    # 回购类
    "回购增持再贷款概念",
})
# 年报/季报预告类板块（年更，名称随年份变化）—— 模式匹配
EXCLUDED_CONCEPT_PATTERNS: tuple[str, ...] = ("预增", "预减", "预盈", "预亏")


def is_excluded_concept(name: str) -> bool:
    """该概念板块是否属于「无业务关联、不在板块营地展示」。"""
    text = str(name or "").strip()
    if not text:
        return False
    if text in EXCLUDED_CONCEPT_NAMES:
        return True
    return any(pattern in text for pattern in EXCLUDED_CONCEPT_PATTERNS)
